def render(sid, acc, eyebrow, title, items, foot):
    lis = "".join('<div class="it"><span class="mk"></span><span class="tx">%s</span></div>' % esc(x)
                  for x in items)
    return ('<style>%s</style><div class="card" style="--acc:%s">'
            '<div class="eyebrow">%s</div><h2>%s</h2>'
            '<div class="list">%s</div><div class="foot">%s</div></div>'
            % (CSS, acc, esc(eyebrow), esc(title), lis, esc(foot)))


for sid, acc, eb, title, items, foot in SIDES:
    p = os.path.join(OUT, sid + ".html")
    open(p, "w", encoding="utf-8").write(render(sid, acc, eb, title, items, foot))
    subprocess.run([CHROME, "--headless", "--disable-gpu", "--hide-scrollbars",
                    "--force-device-scale-factor=2", "--screenshot=" + os.path.join(OUT, sid + ".png"),
                    "--window-size=%d,%d" % (W, H), "--default-background-color=08090B",
                    "file://" + p], capture_output=True)

